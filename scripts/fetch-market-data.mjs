import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'

const tickers = ['AAPL', 'MSFT', 'NVDA', 'SPY', 'QQQ', 'TLT', 'GLD']
const assetClasses = { AAPL: 'stocks', MSFT: 'stocks', NVDA: 'stocks', SPY: 'etf', QQQ: 'etf', TLT: 'etf', GLD: 'etf' }
const fromDate = '2023-07-03'
const toDate = '2026-07-24'
const output = resolve('src/data/marketPrices.ts')

const fetchTicker = async (ticker) => {
  const url = new URL(`https://api.nasdaq.com/api/quote/${ticker.toLowerCase()}/historical`)
  url.search = new URLSearchParams({ assetclass: assetClasses[ticker], fromdate: fromDate, todate: toDate, limit: '5000' }).toString()
  const response = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0 Quant-Risk-Lab educational data snapshot' } })
  if (!response.ok) throw new Error(`${ticker}: Nasdaq returned HTTP ${response.status}`)
  const payload = await response.json()
  const rows = payload?.data?.tradesTable?.rows
  if (!Array.isArray(rows) || rows.length < 500) throw new Error(`${ticker}: incomplete history received`)
  return new Map(rows.map((row) => [toIsoDate(row.date), parseClose(row.close)]).filter(([, close]) => Number.isFinite(close)))
}

const toIsoDate = (value) => {
  const [month, day, year] = value.split('/')
  return `${year}-${month.padStart(2, '0')}-${day.padStart(2, '0')}`
}

const parseClose = (value) => Number(String(value).replace(/[$,]/g, ''))

const series = await Promise.all(tickers.map(async (ticker) => [ticker, await fetchTicker(ticker)]))
const allDates = [...series[0][1].keys()].filter((date) => series.every(([, rows]) => rows.has(date))).sort()
if (allDates.length < 700) throw new Error(`Expected at least 700 aligned observations; received ${allDates.length}`)
const prices = Object.fromEntries(series.map(([ticker, rows]) => [ticker, allDates.map((date) => rows.get(date))]))
const sourceUrls = Object.fromEntries(tickers.map((ticker) => [ticker, `https://api.nasdaq.com/api/quote/${ticker.toLowerCase()}/historical?assetclass=${assetClasses[ticker]}&fromdate=${fromDate}&todate=${toDate}&limit=5000`]))
const generated = `// Generated by scripts/fetch-market-data.mjs on ${new Date().toISOString()}.\n// Source: Nasdaq historical Close/Last endpoint. This file is intentionally committed for static deployment.\n\nexport const marketPrices = ${JSON.stringify({ dates: allDates, prices }, null, 2)} as const\n\nexport const marketPriceSourceUrls = ${JSON.stringify(sourceUrls, null, 2)} as const\n`
await mkdir(dirname(output), { recursive: true })
await writeFile(output, generated, 'utf8')
console.log(`Wrote ${allDates.length} aligned observations for ${tickers.length} assets to ${output}`)
